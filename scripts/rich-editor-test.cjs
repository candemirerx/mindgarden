const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const { MarkdownManager } = require('@tiptap/markdown');
const { getSchema } = require('@tiptap/core');
const { EditorState, TextSelection } = require('@tiptap/pm/state');
const moduleResult = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/richText.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText, { require, exports: moduleResult.exports, module: moduleResult });
const { richTextExtensions, richTextSelection } = moduleResult.exports;
assert.equal(moduleResult.exports.noteTextOnly('önce ![Not görseli](data:image/png;base64,YQ==) sonra'), 'önce [Not görseli] sonra', 'Text-only exports cannot dump binary payloads');
const extensions = richTextExtensions();
const manager = new MarkdownManager({ extensions, markedOptions: { breaks: true, gfm: true } });
const schema = getSchema(extensions);
for (const text of ['**Kalın** ve *italik* ve ~~çizili~~', '## Başlık\n\n- Bir\n- İki', 'Birinci\nİkinci\n\nÜçüncü', '| A | B |\n|---|---|\n| 1 | 2 |', '```js\nconst x = 1\n```', 'İstanbul çğıöşü']) {
    const parsed = manager.parse(text);
    const roundtrip = manager.parse(manager.serialize(parsed));
    assert.equal(schema.nodeFromJSON(roundtrip).textContent, schema.nodeFromJSON(parsed).textContent, 'Formatting roundtrip must keep text');
}
assert.equal(manager.parse('**Kalın**').content[0].content[0].marks[0].type, 'bold');
assert.equal(manager.parse('*Eğik*').content[0].content[0].marks[0].type, 'italic');
const unsafe = manager.parse('<script>alert(1)</script>\n\n![Takip](https://evil.invalid/pixel)');
assert.ok(!JSON.stringify(unsafe).includes('"type":"image"'));
assert.ok(!JSON.stringify(unsafe).includes('"type":"script"'));
const localImage = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==';
const embedded = manager.parse('önce ![Not görseli](' + localImage + ') sonra');
assert.match(JSON.stringify(embedded), /"type":"image"/);
assert.ok(manager.serialize(embedded).includes(localImage));
assert.ok(manager.serialize(manager.parse(manager.serialize(embedded))).includes(localImage));
assert.equal(schema.nodeFromJSON(embedded).textContent, 'önce  sonra');
console.log('OK: Formatting and inline local image Markdown roundtrip; remote tracking images/scripts blocked');
const doc = schema.nodeFromJSON(manager.parse('aynı aynı son'));
const state = EditorState.create({ schema, doc, selection: TextSelection.create(doc, 6, 10) });
const snapshot = richTextSelection({ state, markdown: manager });
assert.equal(snapshot.text, 'aynı');
const replaced = schema.nodeFromJSON(manager.parse(snapshot.replace('**yeni**'))).textContent;
assert.equal(replaced, 'aynı yeni son', 'Only the selected repeated word must change');
assert.equal(state.doc.textContent, 'aynı aynı son', 'Snapshot creation/replacement must not mutate the live editor');
assert.equal(richTextSelection({ state: EditorState.create({ schema, doc }), markdown: manager }), null);
console.log('OK: AI selection snapshots preserve surrounding text and do not mutate the live note');
const editor = fs.readFileSync('app/editor/page.tsx', 'utf8');
const header = editor.slice(editor.indexOf('{/* Header */}'), editor.indexOf('<div className="studio-tools"'));
assert.ok(!header.includes('exportBilgeTree'));
assert.match(editor, /router\.replace\(`\/editor\?id=\$\{encodeURIComponent\(node.garden_id\)/);
assert.match(editor, /if \(!transferred\)/);
assert.match(editor, /readOnly=\{bilgeExporting \|\| resultPending \|\| drawing \|\| imagePreparing\}/);
assert.ok(fs.readFileSync('components/ai/BilgeAgac.tsx', 'utf8').includes("denemeNotuYaz('bilge', title, text)"));
const richComponent = fs.readFileSync('components/editor/RichTextEditor.tsx', 'utf8');
assert.match(richComponent, /setEditable\(!readOnly, false\)/);
assert.match(richComponent, /setMeta\('addToHistory', false\)/);
assert.match(editor, /RichTextEditor key=\{nodeId\}/);
assert.match(richComponent, /toolbar = false/);
assert.match(richComponent, /\{toolbar && <div id="studio-format-toolbar"/);
assert.match(editor, /\[formatToolbar, setFormatToolbar\] = useState\(false\)/);
assert.match(editor, /tool.kind === 'bicim-cubugu'/);
assert.match(editor, /Normal yazıya dön/);
const css = fs.readFileSync('app/editor/studio.css', 'utf8');
assert.match(css, /\.studio-rich-text \.studio-inline-image \{ display: inline-block; width: 72px; height: 60px;/);
for (const file of ['ImagePreview', 'DrawingPad']) {
    assert.match(fs.readFileSync('components/editor/' + file + '.tsx', 'utf8'), /pt-\[calc\(env\(safe-area-inset-top,0px\)/);
}
console.log('OK: Formatting is opt-in, image cards stay compact, preview/drawing headers respect phone safe areas');
const chat = fs.readFileSync('components/ai/BilgeAgac.tsx', 'utf8');
assert.equal((chat.match(/h-\[60px\] w-\[72px\] object-cover/g) || []).length, 2, 'Sent and pending chat photos remain compact too');
console.log('OK: Transfer removed from cramped header; successful transfer opens the saved tree, failure stays retryable; Bilge formatting retained');
